def build_worldline_message(message: str, enabled: bool, mode: str) -> str:
    """为单次世界线请求附加模式指令，不改变普通对话。"""
    if not enabled:
        return message

    instruction = (
        WORLDLINE_IMMERSIVE_INSTRUCTION
        if mode == "immersive"
        else WORLDLINE_OBSERVE_INSTRUCTION
    )
    return f"{instruction}\n\n【用户设置的分歧点】\n{message}"
